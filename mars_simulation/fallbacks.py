import random

# 每个角色多个候选，随机抽取，避免重复出现固定预设句
FALLBACK_POOL = {
    "知识贡献者": ["植物要浇水的", "小鱼要有水", "叶子可以画绿点"],
    "想法提出者": ["加个小池塘吧", "画几块石头吧", "旁边加点草"],
    "协调组织者": ["先把主题定了", "谁画水池啊", "先别吵了"],
    "反思评价者": ["会不会太挤了", "这个能画出来吗", "这放哪儿啊"],
    "社交支持者": ["对", "行", "可以"],
    "消极参与者": ["随便", "你们定", "都行"],
    "争吵促进者": ["你别乱说", "不对不对", "这也太怪了"],
    "干扰者": ["我想画个厕所", "这个像面包机", "我饿了"],
}


def fallback_for_role(role: str) -> str:
    pool = FALLBACK_POOL.get(role, ["嗯", "好", "行"])
    return random.choice(pool)
